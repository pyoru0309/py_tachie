# =============================================================================
# app/version.py
#
# アプリの公開バージョン (single source of truth)。
#
# 全体設定 → アップデートの「現在のバージョン」表示はこの定数を唯一の真実として
# 使う (git describe には依存しない)。git describe は splite_anime に残っている
# stray な `v1.0` タグを拾ってしまい実態と噛み合わないため、表示用バージョンは
# ここで明示管理する。画面では `v{__version__} ({短い git SHA})` の形で出す。
#
# semver + プレリリースラベルで段階を表す:
#   開発中      : "0.3.0-dev"
#   検証 (beta) : "0.3.0-beta.1"
#   RC          : "0.3.0-rc.1"
#   公開         : "0.3.0"
#
# リリース手順: ここを更新 → py_tachie へ同期 (tools/sync_to_public.sh) →
#               公開リポでタグ (例 v0.3.0) を切る。
# =============================================================================

__version__ = "0.4.0-dev"
